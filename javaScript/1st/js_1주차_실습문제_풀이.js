// ------------------------------------------
// 1. let과 const로 각각 변수를 선언하고,
//    왜 하나는 값을 바꿀 수 있고 다른 하나는
//    안 되는지 코드로 확인해 보세요.
// ------------------------------------------

let score = 0;          // let: 재할당 가능한 변수
score = 10;              // (O) 값을 바꿀 수 있음
console.log("score(let):", score);

const PI = 3.14;         // const: 재할당 불가능한 상수
// PI = 3.141592;         // (X) 주석을 풀면 TypeError: Assignment to constant variable.
console.log("PI(const):", PI);

// 이유: let은 "값이 바뀔 수 있는 변수"를 선언할 때 쓰고,
// const는 "값이 고정된 상수"를 선언할 때 쓰기 때문에
// 언어 차원에서 const에 대한 재할당을 막아둔 것입니다.


// ------------------------------------------
// 2. for문을 이용해 1부터 10까지의 합을 구하는
//    코드를 작성해 보세요.
// ------------------------------------------

let sum = 0;
for (let i = 1; i <= 10; i++) {
  sum += i; // sum = sum + i
}
console.log("1부터 10까지의 합:", sum); // 55


// ------------------------------------------
// 3. 1부터 20까지 반복하되, 짝수만 출력하는
//    코드를 continue를 사용해 작성해 보세요.
// ------------------------------------------

console.log("1~20 중 짝수:");
for (let i = 1; i <= 20; i++) {
  if (i % 2 !== 0) {
    continue; // 홀수면 이번 반복은 건너뛰고 다음 숫자로
  }
  console.log(i);
}


// ------------------------------------------
// 4. 1부터 반복하다가 처음으로 7의 배수를 만나면
//    break로 반복을 멈추고 그 숫자를 출력하는
//    코드를 작성해 보세요.
// ------------------------------------------

for (let i = 1; i <= 100; i++) {
  if (i % 7 === 0) {
    console.log("처음 만난 7의 배수:", i); // 7
    break; // 조건을 만족하는 순간 반복문 종료
  }
}
